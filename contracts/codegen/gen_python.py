"""Generate ksl_core/_generated/* from contracts/ (SSOT). Use --check in CI to fail on drift."""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "ksl_core" / "_generated"
HEADER = '"""GENERATED by contracts/codegen/gen_python.py from contracts/. DO NOT EDIT."""\n'


def gen_landmark_spec() -> str:
    spec = json.loads((ROOT / "contracts/landmarks/landmark_spec_v1.json").read_text())
    g = {grp["name"]: grp for grp in spec["groups"]}
    lines = [
        HEADER,
        "from __future__ import annotations\n",
        f"SPEC_VERSION = {spec['spec_version']}",
        f"N_POINTS = {spec['n_points']}",
        f"FEATURE_DIM = {spec['features']['dim']}",
        f"MAGIC = {spec['binary']['magic'].encode()!r}",
        f"HEADER_STRUCT = {spec['binary']['header_struct']!r}",
        f"FRAMES_PER_MESSAGE = {spec['binary']['frames_per_message']}",
    ]
    for name, grp in g.items():
        up = name.upper()
        lines.append(f"N_{up} = {grp['count']}")
        lines.append(f"OFFSET_{up} = {grp['offset']}")
    lines.append(f"FACE_IDX: tuple[int, ...] = {tuple(g['face']['indices'])!r}")
    lines.append(f"POSE_IDX: tuple[int, ...] = {tuple(g['pose']['indices'])!r}")
    lines.append(f"POSE_NAMED: dict[str, int] = {spec['pose_named']!r}")
    lines.append(f"HAND_NAMED: dict[str, int] = {spec['hand_named']!r}")
    lines.append(
        f"FACE_RANGES: dict[str, tuple[int, int]] = { {k: tuple(v) for k, v in g['face']['named_ranges'].items()}!r}"
    )
    return "\n".join(lines) + "\n"


def gen_ws_messages() -> str:
    proto = json.loads((ROOT / "contracts/realtime/ws_protocol_v1.json").read_text())
    errs = json.loads((ROOT / "contracts/realtime/error_codes_v1.json").read_text())
    msgs = proto["messages"]
    lines = [
        HEADER,
        "from __future__ import annotations\n",
        "from enum import IntEnum\n",
        "PROTOCOL_VERSION = 1\n",
        "MESSAGE_TYPES: frozenset[str] = frozenset({",
    ]
    lines += [f"    {t!r}," for t in sorted(msgs)]
    lines.append("})\n")
    lines.append("C2S_TYPES: frozenset[str] = frozenset({")
    lines += [f"    {t!r}," for t, m in sorted(msgs.items()) if m["direction"] in ("c2s", "both")]
    lines.append("})\n")
    lines.append("REQUIRED_FIELDS: dict[str, tuple[str, ...]] = {")
    lines += [f"    {t!r}: {tuple(m['required'])!r}," for t, m in sorted(msgs.items())]
    lines.append("}\n")
    lines.append("BINARY_KINDS: dict[str, int] = " + repr(proto["binary_kinds"]) + "\n")
    lines.append("\nclass ErrorCode(IntEnum):")
    lines += [f"    {e['name']} = {e['code']}" for e in errs["codes"]]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = ap.parse_args()
    outputs = {"landmark_spec.py": gen_landmark_spec(), "ws_messages.py": gen_ws_messages(), "__init__.py": HEADER}
    OUT.mkdir(parents=True, exist_ok=True)
    drift = []
    for name, text in outputs.items():
        p = OUT / name
        if args.check:
            if not p.exists() or p.read_text() != text:
                drift.append(name)
        else:
            p.write_text(text)
    if drift:
        print(f"contract drift in ksl_core/_generated: {drift}. Run `make contracts`.", file=sys.stderr)
        return 1
    print("ksl_core/_generated is up to date" if args.check else f"wrote {len(outputs)} files to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
