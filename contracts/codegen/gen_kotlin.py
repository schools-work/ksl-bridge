"""Generate Kotlin sources for the app repository from contracts/ (landmark spec, WS types, error codes)."""

from __future__ import annotations

import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
PKG = "ke.kslbridge.contracts"
HEADER = "// GENERATED by contracts/codegen/gen_kotlin.py. DO NOT EDIT.\n"


def camel(s: str) -> str:
    parts = s.replace(".", "_").split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def pascal(s: str) -> str:
    return "".join(p.title() for p in s.replace(".", "_").split("_"))


def landmark_spec() -> str:
    spec = json.loads((ROOT / "contracts/landmarks/landmark_spec_v1.json").read_text())
    g = {grp["name"]: grp for grp in spec["groups"]}
    face = ", ".join(map(str, g["face"]["indices"]))
    out = [
        HEADER,
        f"package {PKG}\n",
        "object LandmarkSpec {",
        f"    const val SPEC_VERSION: Int = {spec['spec_version']}",
        f"    const val N_POINTS: Int = {spec['n_points']}",
        f"    const val FRAMES_PER_MESSAGE: Int = {spec['binary']['frames_per_message']}",
        '    const val MAGIC: String = "KSLB"',
    ]
    for name, grp in g.items():
        out.append(f"    const val {name.upper()}_OFFSET: Int = {grp['offset']}")
        out.append(f"    const val {name.upper()}_COUNT: Int = {grp['count']}")
    out.append(f"    val FACE_IDX: IntArray = intArrayOf({face})")
    out.append("}")
    return "\n".join(out) + "\n"


def ws_types() -> str:
    proto = json.loads((ROOT / "contracts/realtime/ws_protocol_v1.json").read_text())
    errs = json.loads((ROOT / "contracts/realtime/error_codes_v1.json").read_text())
    out = [HEADER, f"package {PKG}\n", "object WsMessageType {"]
    for t in sorted(proto["messages"]):
        out.append(f'    const val {t.replace(".", "_").upper()}: String = "{t}"')
    out.append("}\n")
    out.append("enum class WsErrorCode(val code: Int) {")
    out += [f"    {e['name']}({e['code']})," for e in errs["codes"]]
    out.append("    ;\n    companion object { fun of(code: Int) = entries.firstOrNull { it.code == code } }\n}\n")
    out.append("object BinaryKind {")
    for k, v in proto["binary_kinds"].items():
        out.append(f"    const val {k.upper()}: Byte = {v}")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="build/kotlin")
    args = ap.parse_args()
    out = pathlib.Path(args.out) / PKG.replace(".", "/")
    out.mkdir(parents=True, exist_ok=True)
    (out / "LandmarkSpec.kt").write_text(landmark_spec())
    (out / "WsProtocol.kt").write_text(ws_types())
    print(f"wrote Kotlin contracts to {out}")


if __name__ == "__main__":
    main()
